export function declQty(n) {
  const r = Math.abs(n) % 100;
  const r1 = r % 10;
  if (r > 10 && r < 20) return "позиций";
  if (r1 === 1) return "позиция";
  if (r1 >= 2 && r1 <= 4) return "позиции";
  return "позиций";
}
